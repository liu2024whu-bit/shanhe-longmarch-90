export const corridorById=new Map(corridorDefinitions.map(route=>[route.id,route]));
export const waypointById=new Map(waypointSpecs.map(p=>[p.id,p]));
export function resolveWaypoint(id,references={}){
  const spec=waypointById.get(id);
  if(!spec)throw new Error(`Unknown route waypoint: ${id}`);
  const ref=references[id];
  return {...spec,...ref,id,name:spec.name,coordinateMeaning:ref?.coordinateMeaning||(ref?.geonameId?'modern locality reference':'regional editorial reference')};
}
export function resolveSceneLine(step,places,references={}){
  return chishuiSequences[step].refs.map(id=>id.startsWith('@')?resolveWaypoint(id.slice(1),references):places[id]);
}
